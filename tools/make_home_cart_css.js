#!/usr/bin/env node
// Build /assets/ms-home-cart.css: the Tailwind rules the cart drawer and cookie banner need, scoped to
// #cart-drawer and [data-cookie], so the homepage (which does not load BaseLayout.css) can show them
// exactly like every other page without the rest of Tailwind touching the homepage layout.
// Usage (repo root): NODE_PATH=/path/to/node_modules node tools/make_home_cart_css.js   (needs postcss)
const fs = require('fs'), postcss = require('postcss');
const cssFile = fs.readdirSync('_astro').find(f => /^BaseLayout\..*\.css$/.test(f));
const root = postcss.parse(fs.readFileSync('_astro/' + cssFile, 'utf8'));
// class names used by the drawer + cookie markup (shop page) and by the cart script's templates
const shop = fs.readFileSync('shop/index.html', 'utf8'), js = fs.readFileSync('_astro/site-cart.v2.js', 'utf8');
const a = shop.indexOf('<div id="cart-drawer"'), b = shop.indexOf('<script id="shop-config"');
const used = new Set();
for (const m of (shop.slice(a, b) + js).matchAll(/class="([^"$]*(?:\$\{[^}]*\}[^"$]*)*)"/g)) m[1].split(/\s+/).forEach(c => c && used.add(c));
const S = ':is(#cart-drawer,[data-cookie])';
const unesc = s => s.replace(/\\(.)/g, '$1');
const classesOf = sel => [...sel.matchAll(/\.((?:\\.|[\w-])+)/g)].map(m => unesc(m[1]));
const out = [];
const scopeSel = (sel, filter) => sel.split(/,(?![^()]*\))/).map(s => s.trim()).filter(s => {
  if (/^(html|body|:host|:root)\b/.test(s)) return false;
  return !filter || (classesOf(s).length && classesOf(s).every(c => used.has(c)));
}).map(s => `${S} ${s}`).join(',');
function take(node, filter, wrap) {
  node.each(n => {
    if (n.type === 'rule') { const sel = scopeSel(n.selector, filter); if (sel) { const c = n.clone({ selector: sel }); wrap.append(c); } }
    else if (n.type === 'atrule' && /^(media|supports)$/.test(n.name)) { const w = postcss.atRule({ name: n.name, params: n.params, nodes: [] }); take(n, filter, w); if (w.nodes && w.nodes.length) wrap.append(w); }
  });
}
const outRoot = postcss.root();
root.each(n => {
  if (n.type === 'atrule' && n.name === 'layer') {
    if (n.params === 'properties' || n.params === 'theme') n.each(c => outRoot.append(c.clone()));  // --tw-* defaults and :root theme vars (no homepage name clashes)
    else take(n, n.params !== 'base', outRoot);   // base = scoped preflight, components/utilities = only used classes
  } else if (n.type === 'atrule' && (n.name === 'property' || n.name === 'font-face')) outRoot.append(n.clone());  // fonts download only when the drawer/banner shows
});
const head = `/* Generated by tools/make_home_cart_css.js from ${cssFile}: cart drawer + cookie banner styles for the homepage. */\n` +
  `#cart-drawer{position:fixed;inset:0;z-index:50}[data-cookie]{position:fixed;left:0;right:0;bottom:0;z-index:40;padding:.75rem}` +
  `#cart-drawer,[data-cookie]{line-height:1.5;font-family:var(--font-sans);color:var(--color-ink);text-rendering:optimizelegibility}` +
  `button.iconbtn{padding:0;color:inherit}.iconbtn .badge.hidden{display:none}` +
  `@media (min-width:40rem){[data-cookie]{padding:1rem}}#cart-drawer[hidden],[data-cookie][hidden]{display:none!important}\n`;
fs.writeFileSync('assets/ms-home-cart.css', head + outRoot.toString().replace(/\n\s*/g, '') + '\n');
console.log('classes used:', used.size, 'bytes:', fs.statSync('assets/ms-home-cart.css').size);
